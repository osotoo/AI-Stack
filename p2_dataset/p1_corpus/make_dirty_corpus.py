# 1. 读取文件
import pandas as pd
import pathlib

csv_path = pathlib.Path(__file__).parent / "raw_corpus.csv"
df = pd.read_csv(csv_path)

# 练习1: 去掉空数据
print("去空前：", len(df), "条")

# mask：一个普通列表，第 i 个格子回答"第 i 行要不要留"（True 留 / False 丢）
mask = []

# iterrows()：显式要"行"的遍历。每轮给两样东西：行号 i、这一行的内容 row
for i, row in df.iterrows():
    text = row["text"]  # 按列名取，不会错位

    # or 从左往右算，左边为 True 就不看右边（短路）：
    # pd.isna(text) 是 True 时，text.strip() 根本不执行，NaN 在这里不会崩
    # strip() 不带参数能同时吃掉半角空格和全角空格（U+3000 算空白字符）
    if pd.isna(text) or text.strip() == "":
        mask.append(False)  # 这行是空的，标记为丢
    else:
        mask.append(True)  # 这行有内容，标记为留

df = df[mask]  # True 的行留下，False 的行丢掉

print("去空后：", len(df), "条")  # 预期 27（30 − 3）

# 练习2: re 正则
import re

print("去空前：", len(df), "条")

mask = []
for i, row in df.iterrows():
    text = row["text"]
    if re.search(r"\d+[\u4e00-\u9fa5]+", text):
        mask.append(False)
    else:
        mask.append(True)
